/**
 * Gets a consistent Verse of the Day based on the current date,
 * ensuring each day features an inspiring biblical quote.
 */
export function getVerseOfTheDay(date: Date = new Date()): DailyVerse {
  const startOfYear = new Date(date.getFullYear(), 0, 1);
  const diff = date.getTime() - startOfYear.getTime();
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));
  const index = Math.abs(dayOfYear) % DAILY_VERSES.length;
  return DAILY_VERSES[index];
}
